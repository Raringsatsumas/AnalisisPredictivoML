# -------------------------
# Normalización para score relativo
# -------------------------
def minmax(s):
    if s.max() == s.min():
        return pd.Series([0.0] * len(s), index=s.index)
    return (s - s.min()) / (s.max() - s.min())

tabla_clusters["score_lesionados"] = minmax(tabla_clusters["Lesionados promedio"])
tabla_clusters["score_vehiculos"] = minmax(tabla_clusters["Vehículos promedio"])
tabla_clusters["score_fatalidades"] = minmax(tabla_clusters["Fatalidades promedio"])

tabla_clusters["score_tipo"] = np.where(
    tabla_clusters["Tipo de accidente dominante"] == "INJURY AND / OR TOW DUE TO CRASH",
    1.0,
    0.0
)

# penalización ligera si el cluster es demasiado pequeño
tabla_clusters["score_tamano"] = minmax(tabla_clusters["Cantidad de casos"])

# Score total de criticidad
tabla_clusters["Score de criticidad"] = (
    0.40 * tabla_clusters["score_lesionados"] +
    0.20 * tabla_clusters["score_fatalidades"] +
    0.15 * tabla_clusters["score_vehiculos"] +
    0.20 * tabla_clusters["score_tipo"] +
    0.05 * (1 - tabla_clusters["score_tamano"])
)

# -------------------------
# Asignar nivel según ranking relativo
# -------------------------
tabla_clusters = tabla_clusters.sort_values("Score de criticidad", ascending=False).reset_index(drop=True)

