"""##Función Dunn"""

def dunn_index_fast(X, labels):
    clusters = np.unique(labels)
    centroids = np.array([X[labels == c].mean(axis=0) for c in clusters])

    dist_centroids = cdist(centroids, centroids)
    np.fill_diagonal(dist_centroids, np.inf)
    inter = np.min(dist_centroids)

    intra = []
    for i, c in enumerate(clusters):
        cluster_points = X[labels == c]
        dist = np.linalg.norm(cluster_points - centroids[i], axis=1)
        intra.append(np.mean(dist))

    return inter / np.max(intra)

