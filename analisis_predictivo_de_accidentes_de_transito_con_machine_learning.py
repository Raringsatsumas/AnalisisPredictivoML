# -------------------------
# Función para mapear cluster -> clase real más frecuente
# -------------------------
def cluster_to_class_predictions(labels, y_true):
    labels = np.array(labels)
    y_true = np.array(y_true)

    y_pred = np.full_like(y_true, fill_value=-1)

    clusters = np.unique(labels)

    # ignorar ruido de DBSCAN (-1) en el mapeo inicial
    clusters_validos = [c for c in clusters if c != -1]

    mapping = {}
    for c in clusters_validos:
        idx = np.where(labels == c)[0]
        clase = mode(y_true[idx], keepdims=True)[0][0]
        mapping[c] = clase

    # asignar predicción según cluster
    for i, c in enumerate(labels):
        if c in mapping:
            y_pred[i] = mapping[c]

    # si DBSCAN dejó ruido (-1), asignar la clase global más frecuente
    clase_global = mode(y_true, keepdims=True)[0][0]
    y_pred[y_pred == -1] = clase_global

    return y_pred, mapping

