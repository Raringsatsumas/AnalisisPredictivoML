# K-Means
# -------------------------
kmeans_cmp = KMeans(n_clusters=k_optimo, random_state=42, n_init=10)
labels_kmeans = kmeans_cmp.fit_predict(X_cmp)
y_pred_kmeans_cmp, map_kmeans = cluster_to_class_predictions(labels_kmeans, y_cmp)

# -------------------------
# Jerárquico
# -------------------------
jerarquia_cmp = AgglomerativeClustering(n_clusters=k_optimo, linkage='ward')
labels_jerarquia = jerarquia_cmp.fit_predict(X_cmp)
y_pred_jerarquia_cmp, map_jerarquia = cluster_to_class_predictions(labels_jerarquia, y_cmp)

