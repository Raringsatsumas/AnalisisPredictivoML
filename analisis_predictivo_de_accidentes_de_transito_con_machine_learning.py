"""## Selección automática de k óptimo"""

x = np.array(list(k_values))
y = np.array(inertia)

p1 = np.array([x[0], y[0]])
p2 = np.array([x[-1], y[-1]])

distancias = []
for i in range(len(x)):
    p = np.array([x[i], y[i]])
    distancia = np.abs(np.cross(p2 - p1, p1 - p)) / np.linalg.norm(p2 - p1)
    distancias.append(distancia)

distancias = np.array(distancias)
k_codo = x[np.argmax(distancias)]

k_silhouette = x[np.argmax(silhouette)]
k_dunn = x[np.argmax(dunn)]

metricas_k["inercia_norm"] = (
    (metricas_k["inercia"].max() - metricas_k["inercia"]) /
    (metricas_k["inercia"].max() - metricas_k["inercia"].min())
)

metricas_k["silhouette_norm"] = (
    (metricas_k["silhouette"] - metricas_k["silhouette"].min()) /
    (metricas_k["silhouette"].max() - metricas_k["silhouette"].min())
)

metricas_k["dunn_norm"] = (
    (metricas_k["dunn"] - metricas_k["dunn"].min()) /
    (metricas_k["dunn"].max() - metricas_k["dunn"].min())
)

metricas_k["bonus_codo"] = metricas_k["k"].apply(lambda val: 1 if val == k_codo else 0)

metricas_k["score_total"] = (
    0.45 * metricas_k["silhouette_norm"] +
    0.35 * metricas_k["dunn_norm"] +
    0.15 * metricas_k["inercia_norm"] +
    0.05 * metricas_k["bonus_codo"]
)

k_optimo = int(metricas_k.loc[metricas_k["score_total"].idxmax(), "k"])

print("Mejor k según Silhouette:", k_silhouette)
print("Mejor k según Dunn:", k_dunn)
